"""
Freezes the command surface the fman plugin loader discovers.

The loader (fman/impl/plugins/plugin.py:_iterate_classes) only sees classes
reachable as attributes of the top-level `core` package - it walks dir(core),
not the filesystem. So a module split that forgets a `from .x import *` line
silently drops those commands: no import error, no other test failure, they
just stop existing in the app. This test names the missing one.

EXPECTED is regenerated by calling _registered() below, never by a second
copy of the predicate:

	cd src/main/resources/base/Plugins/Core
	PYTHONPATH=../../../../python python -c \
		"from core.tests.test_command_registry import _registered; \
		 print(sorted(_registered()))"
"""
