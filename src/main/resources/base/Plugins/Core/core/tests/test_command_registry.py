def _registered():
	kinds = (ApplicationCommand, DirectoryPaneCommand, DirectoryPaneListener)
	result = set()
	for name in dir(core):
		value = getattr(core, name)
		# [1:] skips the class itself, so the three base classes - which are
		# also attributes of `core` via its star imports - are not counted.
		if inspect.isclass(value) \
				and any(k in inspect.getmro(value)[1:] for k in kinds):
			result.add(name)
	# frozenset, not set: assertEqual only dispatches to the set-difference
	# message when both sides have the same type. A plain set here degrades
	# the failure into a truncated repr that does not name the lost command.
	return frozenset(result)

class CommandRegistryTest(TestCase):
	def test_every_command_is_still_reachable_from_core(self):
		self.assertEqual(EXPECTED, _registered())
